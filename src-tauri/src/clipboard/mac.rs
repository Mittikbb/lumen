//! Thin layer over the macOS pasteboard (NSPasteboard): reading and writing
//! text and images, privacy markers, the app in front and the Cmd+V keystroke.
//! There's no change notification; the watcher polls `changeCount`.

use std::{thread, time::Duration};

use image::RgbaImage;
use objc2_app_kit::{
    NSBitmapImageFileType, NSBitmapImageRep, NSPasteboard, NSPasteboardTypePNG,
    NSPasteboardTypeString, NSPasteboardTypeTIFF,
};
use objc2_core_graphics::{CGEvent, CGEventFlags, CGEventTapLocation};
use objc2_foundation::{NSData, NSDictionary, NSString};

use crate::{front, pixels as img};

/// Virtual key code of "V" (kVK_ANSI_V), the same on every layout.
const KEY_V: u16 = 9;

/// Markers from nspasteboard.org that password managers and other apps put
/// on content clipboard history tools should skip.
const PRIVATE: [&str; 3] = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

pub enum Content {
    Text(String),
    Image(RgbaImage),
}

/// Goes up whenever anything is copied.
pub fn sequence() -> u32 {
    NSPasteboard::generalPasteboard().changeCount() as u32
}

/// Reads what's on the pasteboard, unless it's empty or marked private.
/// Text wins when both are present.
pub fn read() -> Option<(Content, Option<String>)> {
    let pb = NSPasteboard::generalPasteboard();
    if PRIVATE
        .iter()
        .any(|t| pb.dataForType(&NSString::from_str(t)).is_some())
    {
        return None;
    }
    let content = if let Some(text) = pb.stringForType(unsafe { NSPasteboardTypeString }) {
        Content::Text(text.to_string())
    } else if let Some(png) = pb.dataForType(unsafe { NSPasteboardTypePNG }) {
        Content::Image(img::decode_png(&png.to_vec())?)
    } else if let Some(tiff) = pb.dataForType(unsafe { NSPasteboardTypeTIFF }) {
        // Screenshots and most Mac apps offer TIFF.
        let rep = NSBitmapImageRep::imageRepWithData(&tiff)?;
        let png = unsafe {
            rep.representationUsingType_properties(NSBitmapImageFileType::PNG, &NSDictionary::new())
        }?;
        Content::Image(img::decode_png(&png.to_vec())?)
    } else {
        return None;
    };
    // The pasteboard doesn't say who wrote to it; the app in front did.
    Some((content, front::other_app().map(|(_, name)| name)))
}

pub fn write_text(text: &str) -> Result<(), String> {
    let pb = NSPasteboard::generalPasteboard();
    pb.clearContents();
    pb.setString_forType(&NSString::from_str(text), unsafe { NSPasteboardTypeString })
        .then_some(())
        .ok_or_else(|| "pasteboard refused the text".into())
}

pub fn write_image(_image: &RgbaImage, png: &[u8]) -> Result<(), String> {
    let pb = NSPasteboard::generalPasteboard();
    pb.clearContents();
    pb.setData_forType(Some(&NSData::with_bytes(png)), unsafe { NSPasteboardTypePNG })
        .then_some(())
        .ok_or_else(|| "pasteboard refused the image".into())
}

/// The paste keystroke, Cmd+V on macOS, into the app the user was in. Needs
/// Accessibility access (System Settings → Privacy & Security); without it
/// the keystroke is dropped and only the pasteboard is set.
pub fn send_ctrl_v() {
    front::give_back();
    thread::sleep(Duration::from_millis(60));
    for down in [true, false] {
        let Some(event) = CGEvent::new_keyboard_event(None, KEY_V, down) else {
            return;
        };
        CGEvent::set_flags(Some(&event), CGEventFlags::MaskCommand);
        CGEvent::post(CGEventTapLocation::HIDEventTap, Some(&event));
    }
}
